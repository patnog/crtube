void initLocalization(void)
{
   activeLanguage = APP_LANGUAGE_EN;
}

int getAppLanguage(void)
{
   return (int)activeLanguage;
}

const char *getAppLanguageCode(int language)
{
   static const char *const codes[APP_LANGUAGE_COUNT] = { "en", "pt-BR", "es", "fr", "de" };
   if (language < 0 || language >= APP_LANGUAGE_COUNT) return codes[APP_LANGUAGE_EN];
   return codes[language];
}

int setAppLanguage(int language)
{
   if (language < 0 || language >= APP_LANGUAGE_COUNT) return -1;
   activeLanguage = (AppLanguageId)language;
   return 0;
}

const char *getAppLanguageName(int language)
{
   static const char *const names[APP_LANGUAGE_COUNT] = { "English", "Português (Brasil)", "Español", "Français", "Deutsch" };
   if (language < 0 || language >= APP_LANGUAGE_COUNT) return names[APP_LANGUAGE_EN];
   return names[language];
}

const char *localizeString(AppStringId id)
{
   const char *text;

   if ((unsigned)id >= STR_COUNT) return "";
   if ((unsigned)activeLanguage >= APP_LANGUAGE_COUNT)
      activeLanguage = APP_LANGUAGE_EN;

   text = languageCatalogs[activeLanguage][id];
   if (!text) text = languageCatalogs[APP_LANGUAGE_EN][id];
   return text ? text : "";
}
