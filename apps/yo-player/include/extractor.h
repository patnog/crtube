#pragma once

#include <stdint.h>

// extractor - source-agnostic media extraction interface (yt-dlp / NewPipe
// style). Each site (youtube, and later others) implements one Extractor. The
// player never knows which site a stream came from; it just gets a StreamInfo.

#define MAX_STREAM_URL     2048
#define MAX_STREAM_FORMATS 128

// one selectable stream. url may be empty if the source needs deobfuscation we
// haven't done yet (e.g. youtube's cipher) -- formatCount still reflects what
// the source offered.
typedef struct {
   int  itag;              // source-specific format id (0 if n/a)
   int  width, height;
   int  fps;               // frames per second (0 if the source doesn't say)
   int  hasVideo, hasAudio;
   int  needsCipher;       // 1 = url is signature-ciphered, not yet playable
   char container[8];      // "mp4"
   char url[MAX_STREAM_URL];
   char audioTrackId[40];
   char audioTrackName[64];
   int  audioIsDefault;
   int  audioIsAutoDubbed;
   int  isLiveSegmented;   // url is a DASH segment base: fetch "<url>sq/<n>/..." instead of opening it directly
   long liveStartSq;       // earliest segment number available (DVR window start)
   long liveEdgeSq;        // most recent segment number available (live edge)
} StreamFormat;

// Subtitle tracks are allocated to the number actually returned by the extractor.
// one subtitle track offered by the source. url fetches the timed-text file (see subtitles.h).
typedef struct {
   char languageCode[12];   // "en", "es-419"
   char name[48];           // display name, e.g. "English (auto-generated)"
   char url[MAX_STREAM_URL];
   int isAutoGenerated;     // YouTube kind=asr; independent of the localized display name
   int isTranslatable;      // YouTube says this source track can be translated
   int isAutoTranslated;    // synthesized from another track with YouTube's tlang parameter
   int isLocalFile;         // url is a local SRT path rather than a timed-text URL
} CaptionTrack;

typedef struct {
   char title[256];
   char description[2048];   // video description, truncated; newlines are real '\n'
   int  captionCount;
   int  captionCapacity;
   CaptionTrack *captions;
   char defaultAudioTrackId[40];
   int  durationSeconds;
   int  isLive;            // currently broadcasting: streams need live segment-sequence fetching, not a static moov
   int  isPostLive;        // broadcast ended but YouTube still serves its recording as numbered DASH segments
   int  liveDvr;           // broadcaster enabled rewind during the LIVE session
   int  liveSegmentSec;    // target duration of a LIVE segment (normally 5, sometimes 2)
   int  liveWindowSec;     // YouTube's advertised DVR window in seconds
   int  formatCount;
   StreamFormat formats[MAX_STREAM_FORMATS];
   char author[128];       // owning channel name (appended to preserve existing field offsets)
   char viewCount[32];     // raw YouTube videoDetails.viewCount
   char publishedDate[24];// microformat publishDate (ISO date)
} StreamInfo;

// accumulated across pages (infinite scroll); one page is ~20. only the ~30 on-screen tiles hold a
// thumbnail texture + rasterised labels at once (windowed), so this bounds metadata + kept jpegs, not VRAM.
#define MAX_SEARCH_RESULTS 500

// one search hit. videoId is what playVideo() / extract() take; channelId enters that video's channel feed.
typedef struct {
   char videoId[16];
   char channelId[32];     // owning channel's UC id (for "open channel"); empty if not parsed
   char title[160];
   char duration[24];      // "3:15" or playlist video-count badge
   char author[48];        // channel name
   char views[24];         // "6,100 views"
   char published[24];     // "1 hour ago"
   int  isLive;            // 1 = live now (no duration; shown as a red LIVE badge)
   int  isPlaylist;        // 1 = account playlist tile; it is opened by playlistId, not videoId
   char playlistId[64];    // YouTube playlist id, without the VL browse prefix
   char thumbnailVideoId[16]; // first video resolved asynchronously for a playlist tile
   int  isLocalPlaylist;   // PS3-managed playlist; contents are stored locally
   char localPlaylistId[16]; // stable local playlist key (not a YouTube playlist id)
   int  isLocalDownload;
   uint64_t downloadedAt;
   int  checkLiveStatus;     // local history item: resolve current LIVE state asynchronously
   int  liveStatusChecked;   // worker completed the current LIVE-state lookup
} SearchResult;

#define MAX_CONTINUATION 4096   // youtube "load more" tokens are long base64 blobs
#define MAX_SORT_TOKEN   512    // a channel sort chip's continuation token

// Playlist browse failures used by the UI to show an access/unavailable message.
#define PLAYLIST_FETCH_PRIVATE     (-2001)
#define PLAYLIST_FETCH_RESTRICTED  (-2002)
#define PLAYLIST_FETCH_UNAVAILABLE (-2003)

typedef struct {
   int          count;
   char         continuation[MAX_CONTINUATION];   // token for the next page (empty = no more)
   char         channelName[48];                  // viewed channel's title (channel feeds only; else empty)
   // channel Videos feeds carry three sort chips (Latest/Popular/Oldest); each is a continuation token the
   // screen re-browses with. empty outside channel mode. index matches ChannelSort.
   char         sortTokens[3][MAX_SORT_TOKEN];
   SearchResult items[MAX_SEARCH_RESULTS];
} SearchResults;

// trending categories (YouTube retired the single aggregated feed; these are the surviving per-category
// channel-tab feeds). the UI cycles them; keep TrendingNames (home.c) and TRENDING_FEEDS (youtube.c) in sync.
typedef enum {
   TREND_GAMING,
   TREND_SPORTS,
   TREND_PODCASTS,
   TREND_COUNT
} TrendingCategory;

// Live page categories. Keep this order aligned with LIVE_FEEDS in youtube.c
// and LiveNames in home.c.
typedef enum {
   LIVE_POPULAR,
   LIVE_MUSIC,
   LIVE_GAMING,
   LIVE_SPORTS,
   LIVE_PODCASTS,
   LIVE_NEWS,
   LIVE_COUNT
} LiveCategory;

// Search result ordering. Keep the enum aligned with SEARCH_SORT_PARAMS and the search screen labels.
typedef enum {
   SORT_RELEVANCE,
   SORT_VIEWS,
   SORT_NEWEST,
   SORT_COUNT
} SortOrder;

typedef enum {
   PLAYLIST_SORT_NEWEST,
   PLAYLIST_SORT_AZ,
   PLAYLIST_SORT_COUNT
} PlaylistSortOrder;

// a channel Videos feed's sort chips. index matches SearchResults.sortTokens. keep ChannelSortNames in
// the search screen in sync with this order.
typedef enum {
   CHANNEL_SORT_LATEST,
   CHANNEL_SORT_POPULAR,
   CHANNEL_SORT_OLDEST,
   CHANNEL_SORT_COUNT
} ChannelSort;

// the signed-in account's own feeds (see account.h). keep ACCOUNT_FEED_IDS (youtube.c) in this order.
typedef enum {
   ACCOUNT_FEED_HOME,            // Recommended: what youtube.com's home page shows the account
   ACCOUNT_FEED_SUBSCRIPTIONS,   // latest uploads from the account's subscriptions
   ACCOUNT_FEED_HISTORY,         // the account's watch history
   ACCOUNT_FEED_WATCH_LATER,     // the account's Watch Later playlist
   ACCOUNT_FEED_COUNT
} AccountFeed;

typedef struct Extractor {
   const char *name;                                    // "youtube"
   int (*matches)(const char *input);                   // claim this url/id?
   int (*extract)(const char *input, StreamInfo *out);  // 0 ok, negative on error
   // continuation is NULL for the first page, or a prior result's token to fetch the next page.
   int (*search)(const char *query, SortOrder sort, const char *continuation, SearchResults *out);
   int (*getTrending)(TrendingCategory category, const char *continuation, SearchResults *out);
   // a channel's Videos feed. token NULL = first page (Latest); else a sort-chip or next-page token.
   int (*getChannel)(const char *channelId, const char *token, SearchResults *out);
   // a signed-in account feed. continuation as for search. -1 when signed out.
   int (*getAccountFeed)(AccountFeed feed, const char *continuation, SearchResults *out);
   // Resolve a video's owning channel without fetching playback formats.
   int (*getVideoChannelId)(const char *videoId, char *channelId, int channelIdCap);
   // Fetch public video metadata using a WEB player request. Blocking; call on a worker thread.
   int (*getVideoMetadata)(const char *videoId,
                           char *viewCount, int viewCountCap,
                           char *publishedDate, int publishedDateCap,
                           char *likeCount, int likeCountCap);
   // Check whether a video is restricted to channel members. Blocking; call on a worker thread.
   // Returns 1 for members-only, 0 for public/other, negative on request failure.
   int (*isVideoMembersOnly)(const char *videoId);
   // Live streams feed. Appended to preserve the positional initializer above.
   int (*getLive)(LiveCategory category, const char *continuation, SearchResults *out, int (*stopped)(void));
   // A channel's Streams tab, filtered to broadcasts that are live right now.
   int (*getChannelLive)(const char *channelId, SearchResults *out);
   // Signed-in account playlists and the videos inside one playlist. Blocking; call on a worker thread.
   int (*getAccountPlaylists)(const char *continuation, SearchResults *out);
   int (*getAccountPlaylistVideos)(const char *playlistId, const char *continuation, SearchResults *out);
   // Resolve membership restriction and current LIVE state in one player request.
   int (*getVideoStatus)(const char *videoId, int *isLive);
   // Channel categories: 0 Videos, 1 Streams, 2 Shorts, 3 Playlists.
   int (*getChannelCategory)(const char *channelId, int category, const char *continuation, SearchResults *out);
} Extractor;

// picks the first registered extractor that claims input, or NULL.
const Extractor *findExtractor(const char *input);

// text search. continuation NULL = first page, else a prior result's token. 0 ok, negative on error.
int searchVideos(const char *query, SortOrder sort, const char *continuation, SearchResults *out);

// a trending category feed (the launch/home screen). continuation as above. 0 ok, negative on error.
int getTrending(TrendingCategory category, const char *continuation, SearchResults *out);

// A Live category feed. Continuation tokens are opaque to the caller.
int getLiveFeed(LiveCategory category, const char *continuation, SearchResults *out, int (*stopped)(void));

// a channel's Videos feed. token NULL = first page; else a sort-chip token (SearchResults.sortTokens) or a
// next-page continuation. the first page also fills out->sortTokens. 0 ok, negative on error.
int getChannelVideos(const char *channelId, const char *token, SearchResults *out);
// Fetch currently-live broadcasts from a channel's Streams tab. Blocking; call on a worker thread.
int getChannelLiveVideos(const char *channelId, SearchResults *out);
int getChannelCategoryFeed(const char *channelId, int category, const char *continuation, SearchResults *out);

// a signed-in account feed (see AccountFeed). continuation as above. 0 ok; negative on error or when
// signed out. blocking: call from a worker thread.
int getAccountFeed(AccountFeed feed, const char *continuation, SearchResults *out);
int getAccountPlaylists(const char *continuation, SearchResults *out);
int getAccountPlaylistVideos(const char *playlistId, const char *continuation, SearchResults *out);

// Resolve a video's owning channel ID on demand. Blocking network request.
int getVideoChannelId(const char *videoId, char *channelId, int channelIdCap);

// Resolve the first playable recommendation from YouTube's WEB /next response.
int getNextVideoId(const char *videoId, char *nextVideoId, int nextVideoIdCap, char *nextTitle, int nextTitleCap, const char watchedIds[][12], int watchedCount);
